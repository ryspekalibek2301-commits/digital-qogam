let currentCase = null;

function showCase(type) {
  currentCase = cases[type];

  const result = document.getElementById("result");

  result.innerHTML = `
    <h3>${currentCase.title}</h3>
    <p><strong>Жағдай:</strong> ${currentCase.problem}</p>
    <h4>${currentCase.question}</h4>

    <div class="choice-buttons">
      ${currentCase.options.map((option, index) => `
        <button onclick="checkAnswer(${index})">
          ${option.text}
        </button>
      `).join("")}
    </div>

    <div id="feedback" aria-live="polite"></div>
  `;
}

function checkAnswer(index) {
  if (!currentCase) return;

  const selected = currentCase.options[index];
  const feedback = document.getElementById("feedback");

  feedback.innerHTML = `
    <div class="feedback-box">
      <h4>
        ${selected.suitable
          ? "✅ Ұсынылған шешімге сәйкес"
          : "⚠️ Қайта қарауды қажет ететін шешім"}
      </h4>
      <p>${selected.explanation}</p>
      <p>
        <strong>Теориялық байланыс:</strong>
        Әлеуметтік мемлекеттің мақсаты азаматтардың
        әлеуметтік құқықтарын іс жүзінде жүзеге
        асыруына жағдай жасау болып табылады.
      </p>
    </div>
  `;
}

